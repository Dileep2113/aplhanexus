"""Immutable Prediction Registry.

Maintains an immutable, append-only record of every trading recommendation
generated by the application with full technical, fundamental, catalyst,
and cost attribution. Revisions are tracked as linked new records.
"""

from __future__ import annotations

import json
import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

from analyst.database import DEFAULT_DB_PATH, get_db_connection, init_database


@dataclass
class PredictionRecord:
    id: str
    symbol: str
    exchange: str
    timestamp: str
    session_date: str
    direction: str
    setup_type: str
    entry_price: float
    entry_zone_low: float
    entry_zone_high: float
    stop_loss: float
    target1: float
    target2: float
    holding_period: str = "INTRADAY"
    parent_prediction_id: Optional[str] = None
    market_regime: Optional[str] = None
    technical_indicators: Dict[str, Any] = field(default_factory=dict)
    rvol: Optional[float] = None
    vwap_relation: Optional[str] = None
    sector_signal: Optional[str] = None
    global_signal: Optional[str] = None
    catalysts: List[Dict[str, Any]] = field(default_factory=list)
    fundamental_context: Dict[str, Any] = field(default_factory=dict)
    strategy_version: str = "v1.0.0"
    scoring_weights: Dict[str, Any] = field(default_factory=dict)
    confidence_score: float = 0.0
    calibrated_confidence: float = 0.0
    cost_estimate: Dict[str, Any] = field(default_factory=dict)
    selection_reasons: str = ""
    failure_reasons: str = ""
    status: str = "ACTIVE"
    created_at: str = field(default_factory=lambda: datetime.now().isoformat())


class PredictionRegistry:
    """Provides immutable write and query capabilities for trade predictions."""

    def __init__(self, db_path: Path | str = DEFAULT_DB_PATH):
        self.db_path = Path(db_path)
        init_database(self.db_path)

    def register(self, record: PredictionRecord) -> str:
        """Register a new prediction. Never overwrites existing records."""
        with get_db_connection(self.db_path) as conn:
            # Check for existing ID
            existing = conn.execute("SELECT id FROM predictions WHERE id = ?", (record.id,)).fetchone()
            if existing:
                raise ValueError(f"Prediction ID {record.id} already exists. Predictions are immutable!")

            conn.execute("""
                INSERT INTO predictions (
                    id, parent_prediction_id, symbol, exchange, timestamp, session_date,
                    direction, setup_type, entry_price, entry_zone_low, entry_zone_high,
                    stop_loss, target1, target2, holding_period, market_regime,
                    technical_indicators_json, rvol, vwap_relation, sector_signal,
                    global_signal, catalysts_json, fundamental_context_json,
                    strategy_version, scoring_weights_json, confidence_score,
                    calibrated_confidence, cost_estimate_json, selection_reasons,
                    failure_reasons, status, created_at
                ) VALUES (
                    ?, ?, ?, ?, ?, ?,
                    ?, ?, ?, ?, ?,
                    ?, ?, ?, ?, ?,
                    ?, ?, ?, ?,
                    ?, ?, ?,
                    ?, ?, ?,
                    ?, ?, ?,
                    ?, ?, ?
                )
            """, (
                record.id,
                record.parent_prediction_id,
                record.symbol,
                record.exchange,
                record.timestamp,
                record.session_date,
                record.direction,
                record.setup_type,
                record.entry_price,
                record.entry_zone_low,
                record.entry_zone_high,
                record.stop_loss,
                record.target1,
                record.target2,
                record.holding_period,
                record.market_regime,
                json.dumps(record.technical_indicators, default=str),
                record.rvol,
                record.vwap_relation,
                record.sector_signal,
                record.global_signal,
                json.dumps(record.catalysts, default=str),
                json.dumps(record.fundamental_context, default=str),
                record.strategy_version,
                json.dumps(record.scoring_weights, default=str),
                record.confidence_score,
                record.calibrated_confidence,
                json.dumps(record.cost_estimate, default=str),
                record.selection_reasons,
                record.failure_reasons,
                record.status,
                record.created_at,
            ))
        return record.id

    def create_revision(self, parent_id: str, updates: Dict[str, Any]) -> str:
        """Create a new linked revision record without modifying the parent."""
        parent = self.get(parent_id)
        if not parent:
            raise KeyError(f"Parent prediction {parent_id} not found.")

        # Mark parent as SUPERSEDED or keep parent as ACTIVE with parent reference
        new_data = asdict(parent)
        new_data["id"] = f"pred_{uuid.uuid4().hex[:12]}"
        new_data["parent_prediction_id"] = parent_id
        new_data["created_at"] = datetime.now().isoformat()

        for k, v in updates.items():
            if k in new_data and k != "id":
                new_data[k] = v

        new_record = PredictionRecord(**new_data)
        self.register(new_record)

        # Update parent status to REVISED
        with get_db_connection(self.db_path) as conn:
            conn.execute("UPDATE predictions SET status = 'REVISED' WHERE id = ?", (parent_id,))

        return new_record.id

    def update_status(self, prediction_id: str, new_status: str) -> None:
        """Update the lifecycle status of a prediction."""
        with get_db_connection(self.db_path) as conn:
            conn.execute("UPDATE predictions SET status = ? WHERE id = ?", (new_status, prediction_id))

    def get(self, prediction_id: str) -> Optional[PredictionRecord]:
        """Fetch a prediction by its unique ID."""
        with get_db_connection(self.db_path) as conn:
            row = conn.execute("SELECT * FROM predictions WHERE id = ?", (prediction_id,)).fetchone()
            if not row:
                return None
            return self._row_to_record(row)

    def list_for_date(self, session_date: str) -> List[PredictionRecord]:
        """List all predictions registered for a given date."""
        with get_db_connection(self.db_path) as conn:
            rows = conn.execute(
                "SELECT * FROM predictions WHERE session_date = ? ORDER BY timestamp ASC",
                (session_date,)
            ).fetchall()
            return [self._row_to_record(r) for r in rows]

    def list_all(self, limit: int = 100) -> List[PredictionRecord]:
        """List most recent predictions."""
        with get_db_connection(self.db_path) as conn:
            rows = conn.execute(
                "SELECT * FROM predictions ORDER BY timestamp DESC LIMIT ?",
                (limit,)
            ).fetchall()
            return [self._row_to_record(r) for r in rows]

    def _row_to_record(self, row: sqlite3.Row) -> PredictionRecord:
        return PredictionRecord(
            id=row["id"],
            parent_prediction_id=row["parent_prediction_id"],
            symbol=row["symbol"],
            exchange=row["exchange"],
            timestamp=row["timestamp"],
            session_date=row["session_date"],
            direction=row["direction"],
            setup_type=row["setup_type"],
            entry_price=float(row["entry_price"]),
            entry_zone_low=float(row["entry_zone_low"]),
            entry_zone_high=float(row["entry_zone_high"]),
            stop_loss=float(row["stop_loss"]),
            target1=float(row["target1"]),
            target2=float(row["target2"]),
            holding_period=row["holding_period"],
            market_regime=row["market_regime"],
            technical_indicators=json.loads(row["technical_indicators_json"] or "{}"),
            rvol=float(row["rvol"]) if row["rvol"] is not None else None,
            vwap_relation=row["vwap_relation"],
            sector_signal=row["sector_signal"],
            global_signal=row["global_signal"],
            catalysts=json.loads(row["catalysts_json"] or "[]"),
            fundamental_context=json.loads(row["fundamental_context_json"] or "{}"),
            strategy_version=row["strategy_version"],
            scoring_weights=json.loads(row["scoring_weights_json"] or "{}"),
            confidence_score=float(row["confidence_score"] or 0.0),
            calibrated_confidence=float(row["calibrated_confidence"] or 0.0),
            cost_estimate=json.loads(row["cost_estimate_json"] or "{}"),
            selection_reasons=row["selection_reasons"] or "",
            failure_reasons=row["failure_reasons"] or "",
            status=row["status"],
            created_at=row["created_at"],
        )
